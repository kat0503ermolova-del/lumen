// Праздники, цитаты и поздравления

const pad = (n) => String(n).padStart(2, '0');
const key = (y, m, d) => `${y}-${pad(m + 1)}-${pad(d)}`;

// Православная Пасха (юлианский алгоритм Меёса + 13 дней, верно для 1900–2099)
function orthodoxEaster(y) {
  const a = y % 4, b = y % 7, c = y % 19;
  const d = (19 * c + 15) % 30;
  const e = (2 * a + 4 * b - d + 34) % 7;
  const month = Math.floor((d + e + 114) / 31) - 1;
  const day = ((d + e + 114) % 31) + 1;
  return new Date(y, month, day + 13);
}

// Католическая Пасха (григорианский алгоритм)
function westernEaster(y) {
  const a = y % 19, b = Math.floor(y / 100), c = y % 100;
  const d = Math.floor(b / 4), e = b % 4, f = Math.floor((b + 8) / 25);
  const g = Math.floor((b - f + 1) / 3);
  const h = (19 * a + b - d - g + 15) % 30;
  const i = Math.floor(c / 4), k = c % 4;
  const l = (32 + 2 * e + 2 * i - h - k) % 7;
  const m = Math.floor((a + 11 * h + 22 * l) / 451);
  const month = Math.floor((h + l - 7 * m + 114) / 31) - 1;
  const day = ((h + l - 7 * m + 114) % 31) + 1;
  return new Date(y, month, day);
}

const shift = (date, days) => new Date(date.getFullYear(), date.getMonth(), date.getDate() + days);
const dkey = (dt) => key(dt.getFullYear(), dt.getMonth(), dt.getDate());

function lastWeekday(y, m, weekday) {
  const d = new Date(y, m + 1, 0);
  while (d.getDay() !== weekday) d.setDate(d.getDate() - 1);
  return d;
}

// Официальные переносы выходных по производственному календарю РФ
const RU_TRANSFERS = {
  2026: ['2026-01-09', '2026-03-09', '2026-05-11', '2026-12-31'],
};

const cache = new Map();

/** Возвращает { 'YYYY-MM-DD': [{ name, off, kind: 'ru' | 'intl' | 'ru-note' }] } */
export function holidaysFor(year) {
  if (cache.has(year)) return cache.get(year);
  const map = {};
  const add = (k, name, kind, off = false) => {
    (map[k] ||= []).push({ name, kind, off });
  };

  // Официальные выходные праздники РФ
  for (let d = 1; d <= 8; d++) {
    const name = d === 1 ? 'Новый год' : d === 7 ? 'Рождество Христово' : 'Новогодние каникулы';
    add(key(year, 0, d), name, 'ru', true);
  }
  const ruOff = [
    [1, 23, 'День защитника Отечества'],
    [2, 8, 'Международный женский день'],
    [4, 1, 'Праздник Весны и Труда'],
    [4, 9, 'День Победы'],
    [5, 12, 'День России'],
    [10, 4, 'День народного единства'],
  ];
  for (const [m, d, name] of ruOff) add(key(year, m, d), name, 'ru', true);

  // Переносы: точные — если известны, иначе праздник в выходной переносится на понедельник
  if (RU_TRANSFERS[year]) {
    for (const k of RU_TRANSFERS[year]) add(k, 'Перенесённый выходной', 'ru', true);
  } else {
    for (const [m, d] of ruOff) {
      const dt = new Date(year, m, d);
      const dow = dt.getDay();
      if (dow === 6 || dow === 0) add(dkey(shift(dt, dow === 6 ? 2 : 1)), 'Перенесённый выходной', 'ru', true);
    }
  }

  // Памятные дни РФ (рабочие)
  const ruNotes = [
    [0, 14, 'Старый Новый год'],
    [0, 25, 'Татьянин день'],
    [3, 12, 'День космонавтики'],
    [5, 1, 'День защиты детей'],
    [6, 8, 'День семьи, любви и верности'],
    [8, 1, 'День знаний'],
    [9, 5, 'День учителя'],
    [11, 31, 'Канун Нового года'],
  ];
  for (const [m, d, name] of ruNotes) add(key(year, m, d), name, 'ru-note');
  add(dkey(lastWeekday(year, 10, 0)), 'День матери', 'ru-note');

  const easter = orthodoxEaster(year);
  add(dkey(easter), 'Пасха', 'ru-note');
  add(dkey(shift(easter, -55)), 'Масленица', 'ru-note');
  add(dkey(shift(easter, -49)), 'Прощёное воскресенье', 'ru-note');
  add(dkey(shift(easter, 49)), 'Троица', 'ru-note');

  // Международные
  const intl = [
    [1, 14, 'День святого Валентина'],
    [2, 20, 'Международный день счастья'],
    [3, 1, 'День смеха'],
    [3, 22, 'День Земли'],
    [9, 1, 'Международный день музыки'],
    [9, 31, 'Хэллоуин'],
    [10, 13, 'Всемирный день доброты'],
    [11, 25, 'Католическое Рождество'],
  ];
  for (const [m, d, name] of intl) add(key(year, m, d), name, 'intl');
  add(dkey(westernEaster(year)), 'Католическая Пасха', 'intl');

  cache.set(year, map);
  return map;
}

export function holidaysOn(k) {
  return holidaysFor(Number(k.slice(0, 4)))[k] || [];
}

export function isOffDay(k, dow) {
  if (dow === 0 || dow === 6) return true;
  return holidaysOn(k).some((h) => h.off);
}

